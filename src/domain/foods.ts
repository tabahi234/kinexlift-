/**
 * The food table.
 *
 * Curated by hand, like the exercise library, and for the same reason: the
 * fields that matter here are a realistic household serving and an honest
 * macro split, and open food datasets are full of barcode entries with neither.
 *
 * Every dish carries the region it belongs to, and the app asks her country
 * once so it can lead with hers. A woman eating roti, daal and salan every day
 * should not have to translate her dinner into chicken and broccoli to use a
 * food log - and neither should a woman eating jollof, adobo or tortillas. A
 * protein target you cannot hit with the food actually in your kitchen is a
 * target you abandon in a fortnight.
 *
 * Nothing is ever *hidden* by region. The region decides the order of a list
 * and which anchors a generated day reaches for first; every food stays
 * searchable, because plenty of people cook outside their postcode.
 *
 * Values are per the stated serving, from composition tables (USDA FoodData
 * Central and the Indian Food Composition Tables), rounded. Home cooking
 * varies - a karahi made with half a cup of oil is not the karahi below - so
 * these are planning numbers, and the UI says so.
 */

export type Allergen =
  | 'meat'
  | 'pork'
  | 'fish'
  | 'egg'
  | 'dairy'
  | 'gluten'
  | 'nuts'
  | 'soy';

export type FoodGroup = 'protein' | 'carb' | 'veg' | 'fruit' | 'dairy' | 'fat' | 'mixed';

export interface Food {
  id: string;
  name: string;
  /** How she would actually describe one portion. */
  serving: string;
  servingG: number;
  kcal: number;
  proteinG: number;
  carbG: number;
  fatG: number;
  fibreG: number;
  /** Approximate. Included because iron deficiency is common in women. */
  ironMg: number;
  contains: Allergen[];
  group: FoodGroup;
  /**
   * Where this is an everyday food. Absent means everywhere: eggs, rice,
   * yogurt, oats and chicken breast are nobody's regional speciality, and
   * tagging them would push them below a dish she eats twice a year.
   */
  cuisines?: Cuisine[];
  /**
   * What else she might type looking for it. Searching "lentils" and being
   * told the table has nothing is what makes a curated table feel small;
   * it has daal, it just does not spell it that way.
   */
  aliases?: string[];
  /**
   * Something a person eats between meals, as it comes.
   *
   * An opt-in tag rather than a rule about groups, because the rule produced
   * "Snack: 50 g of cooked chicken breast". The arithmetic was right - it is
   * under the calorie ceiling and it is a protein - and nobody has ever
   * snacked on half a chicken breast.
   */
  snack?: boolean;
  /**
   * Powder, not food. It stays in the search and in the protein-gap list,
   * where it is genuinely the best answer, and it is barred from anchoring a
   * meal: a planner that opens lunch with a scoop of whey is a planner that
   * has confused hitting a number with feeding somebody.
   */
  supplement?: boolean;
}

