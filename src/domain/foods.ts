/**
 * Food she entered herself.
 *
 * A curated table is the reason the search is usable, and it is also the
 * reason it will never have her mother's biryani in it. The honest answer to
 * that is not a bigger table - it is letting her write the row, and being
 * clear on the screen about which rows she wrote.
 *
 * The id is a slug so the same dish logged twice groups in the quick-add
 * tally, and it is prefixed so nothing can ever collide with a real entry or
 * be mistaken for one by the coach's catalogue.
 */
export const CUSTOM_PREFIX = 'custom:';

export function customFoodId(name: string): string {
  const slug = name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 40);
  return `${CUSTOM_PREFIX}${slug || 'food'}`;
}

export function isCustomId(id: string): boolean {
  return id.startsWith(CUSTOM_PREFIX);
}

/** The row's food, whether it came from the table or from her. */
export function foodFor(meal: {
  foodId: string;
  custom?: CustomFood;
}): Food | undefined {
  if (meal.custom) {
    return {
      id: meal.foodId,
      name: meal.custom.name,
      serving: meal.custom.serving,
      // Unknown, and it is never shown for a custom food. Zero would read as
      // a claim; this is the one field she was not asked for.
      servingG: 0,
      kcal: meal.custom.kcal,
      proteinG: meal.custom.proteinG,
      carbG: meal.custom.carbG,
      fatG: meal.custom.fatG,
      fibreG: meal.custom.fibreG,
      ironMg: meal.custom.ironMg,
      // She was not asked what is in it, so nothing is claimed about
      // allergens. A custom row is never offered by the planner, only logged.
      contains: [],
      group: 'mixed',
    };
  }
  return BY_ID.get(meal.foodId);
}

