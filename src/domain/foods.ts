function allowedByPattern(food: Food, pattern: DietPattern): boolean {
  switch (pattern) {
    case 'vegan':
      return !food.contains.some((item) =>
        (['meat', 'pork', 'fish', 'egg', 'dairy'] as Allergen[]).includes(item),
      );
    case 'vegetarian':
      return !food.contains.some((item) =>
        (['meat', 'pork', 'fish'] as Allergen[]).includes(item),
      );
    case 'halal':
      return !food.contains.includes('pork');
    case 'omnivore':
      return true;
  }
}

/**
 * Everything she can eat. A food is excluded if her diet pattern rules it out
 * or if it contains anything on her avoid list - and the two are separate,
 * because "I do not eat meat" and "dairy makes me ill" fail differently and a
 * meal plan has to respect both.
 */
export function allowedFoods(pattern: DietPattern, avoid: string[]): Food[] {
  return FOODS.filter(
    (food) =>
      allowedByPattern(food, pattern) &&
      !food.contains.some((item) => avoid.includes(item)),
  );
}

/* --------------------------- region and search --------------------------- */

/**
 * A food with no region on it is an everyday item everywhere - eggs, oats,
 * chicken breast, milk. Those sort above other people's regional cooking and
 * below her own.
 */
export function isUniversal(food: Food): boolean {
  return food.cuisines === undefined || food.cuisines.length === 0;
}

export function isFrom(food: Food, cuisine: Cuisine | null): boolean {
  return cuisine !== null && (food.cuisines?.includes(cuisine) ?? false);
}

/**
 * Her cooking first, then the things everyone eats, then everything else -
 * and inside each band the table's own order, which is already curated.
 *
 * Nothing is removed. She may well cook Thai on a Tuesday, and a food table
 * that hides it because she once tapped "Pakistan" is a table she stops
 * trusting the first time it cannot find her dinner.
 */
export function sortForCuisine(foods: Food[], cuisine: Cuisine | null): Food[] {
  const rank = (food: Food): number =>
    isFrom(food, cuisine) ? 0 : isUniversal(food) ? 1 : 2;
  return foods
    .map((food, index) => ({ food, index }))
    .sort((a, b) => rank(a.food) - rank(b.food) || a.index - b.index)
    .map((entry) => entry.food);
}

/**
 * Does this food answer that search?
 *
 * Name and aliases both, because "lentils" and "yogurt" are what she types and
 * "Daal (masoor or moong)" and "Dahi" are what the table calls them. A
 * curated table only feels small when the search cannot find what is in it.
 */
export function foodMatches(food: Food, query: string): boolean {
  const needle = query.trim().toLowerCase();
  if (needle === '') return true;
  if (food.name.toLowerCase().includes(needle)) return true;
  return (food.aliases ?? []).some((alias) => alias.includes(needle));
}

/**
 * Search results, best first: a name that starts with what she typed beats a
 * name that merely contains it, and both beat an alias match.
 */
export function searchFoods(
  foods: Food[],
  query: string,
  cuisine: Cuisine | null,
): Food[] {
  const needle = query.trim().toLowerCase();
  if (needle === '') return sortForCuisine(foods, cuisine);

  const scored = foods
    .map((food) => {
      const name = food.name.toLowerCase();
      if (name.startsWith(needle)) return { food, score: 0 };
      if (name.includes(needle)) return { food, score: 1 };
      if ((food.aliases ?? []).some((alias) => alias.startsWith(needle)))
        return { food, score: 2 };
      if ((food.aliases ?? []).some((alias) => alias.includes(needle)))
        return { food, score: 3 };
      return null;
    })
    .filter((entry): entry is { food: Food; score: number } => entry !== null);

  // Her own region breaks a tie inside a score band, so searching "curry"
  // in Lahore leads with karahi rather than with Thai green curry.
  return scored
    .sort(
      (a, b) =>
        a.score - b.score ||
        (isFrom(a.food, cuisine) ? 0 : 1) - (isFrom(b.food, cuisine) ? 0 : 1),
    )
    .map((entry) => entry.food);
}

export interface Nutrients {
  kcal: number;
  proteinG: number;
  carbG: number;
  fatG: number;
  fibreG: number;
  ironMg: number;
}

export const NO_NUTRIENTS: Nutrients = {
  kcal: 0,
  proteinG: 0,
  carbG: 0,
  fatG: 0,
  fibreG: 0,
  ironMg: 0,
};

export function scale(food: Food, servings: number): Nutrients {
  return {
    kcal: food.kcal * servings,
    proteinG: food.proteinG * servings,
    carbG: food.carbG * servings,
    fatG: food.fatG * servings,
    fibreG: food.fibreG * servings,
    ironMg: food.ironMg * servings,
  };
}

export function addNutrients(a: Nutrients, b: Nutrients): Nutrients {
  return {
    kcal: a.kcal + b.kcal,
    proteinG: a.proteinG + b.proteinG,
    carbG: a.carbG + b.carbG,
    fatG: a.fatG + b.fatG,
    fibreG: a.fibreG + b.fibreG,
    ironMg: a.ironMg + b.ironMg,
  };
}

export function roundNutrients(value: Nutrients): Nutrients {
  return {
    kcal: Math.round(value.kcal),
    proteinG: Math.round(value.proteinG),
    carbG: Math.round(value.carbG),
    fatG: Math.round(value.fatG),
    fibreG: Math.round(value.fibreG * 10) / 10,
    ironMg: Math.round(value.ironMg * 10) / 10,
  };
}

